"""Content Forensics — detect AI-generated text in reviews and dispute narratives.

Pipeline:
    1. Signals per text (interpretable, no black-box first):
         burstiness (sentence-length coefficient of variation), lexical
         diversity (TTR + moving-average TTR), textstat readability,
         punctuation/caps/exclamation rates, first-person rate, and TF-IDF
         template-reuse similarity against TRAIN flagged texts only.
    2. Three detectors, reported separately:
         - rule threshold on burstiness + readability (transparent baseline)
         - logistic regression on the full signal vector
         - Claude zero-shot judgment with reasons (the reasoning layer)
    3. Flagged texts become Case objects with evidence + reasoning_text,
       appended to the SQLite audit log.

Methodological notes (documented in the metrics JSON):
    - The held-out split is GROUP-BASED for AI texts: held-out topics were
      never used in training, so template-reuse must generalize rather than
      memorize our own generation phrasing.
    - AI texts were generated by different model families (minimax/gemma via
      OpenRouter free tier) than the detector (Claude), avoiding
      self-recognition bias.
    - Length band matched between classes so length is not a giveaway.

Usage:
    .venv/bin/python -m agents.content_forensics [--limit-llm N]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.metrics.pairwise import cosine_similarity

import textstat
from eval.cost_table import decide
from eval.metrics import binary_metrics, format_report, pr_auc
from spine.db import DEFAULT_DB_PATH, connect, count_cases, insert_cases
from spine.llm import chat_json
from spine.schema import Case, Evidence

ROOT = Path(__file__).resolve().parents[1]
DATASET_PATH = ROOT / "data" / "processed" / "content_forensics_labeled.csv"
RESULTS_DIR = ROOT / "eval" / "results"

HELDOUT_GROUP_FRACTION = 0.30

RULES: dict[str, dict] = {
    "low_burstiness": {
        "weight": 0.30,
        "desc": "sentence-length variance below the human floor (uniform, machine-like rhythm)",
    },
    "high_readability": {
        "weight": 0.20,
        "desc": "readability grade above the human ceiling (polished, textbook phrasing)",
    },
    "template_reuse": {
        "weight": 0.30,
        "desc": "TF-IDF similarity to known AI-generated texts above the reuse threshold",
    },
    "low_lexical_diversity": {
        "weight": 0.20,
        "desc": "vocabulary repetition above the human ceiling",
    },
}


# ---------------------------------------------------------------------------
# Signals
# ---------------------------------------------------------------------------

def split_sentences(text: str) -> list[str]:
    return [s.strip() for s in re.split(r"[.!?]+", text) if s.strip()]


def compute_signals(text: str) -> dict:
    """Interpretable AI-text signals for one document."""
    words = re.findall(r"[A-Za-z']+", text.lower())
    sentences = split_sentences(text)
    n_words = max(len(words), 1)
    n_sent = max(len(sentences), 1)

    slens = [len(re.findall(r"[A-Za-z']+", s)) for s in sentences] or [n_words]
    mean_sl = float(np.mean(slens))
    std_sl = float(np.std(slens))
    burstiness = std_sl / mean_sl if mean_sl > 0 else 0.0    # CV of sentence length

    # Moving-average type-token ratio (length-robust lexical diversity).
    window = 40
    ratios = []
    for i in range(max(len(words) - window + 1, 1)):
        chunk = words[i : i + window]
        if chunk:                      # empty text has no windows to average
            ratios.append(len(set(chunk)) / len(chunk))
    mattr = float(np.mean(ratios)) if ratios else 0.0

    first_person = sum(1 for w in words if w in ("i", "i'm", "me", "my", "mine"))
    return {
        "n_sentences": n_sent,
        "mean_sentence_len": mean_sl,
        "burstiness": burstiness,
        "mattr": mattr,                                   # lexical diversity
        "flesch_reading_ease": textstat.flesch_reading_ease(text),
        "flesch_kincaid_grade": textstat.flesch_kincaid_grade(text),
        "exclamation_rate": text.count("!") / n_sent,
        "caps_ratio": sum(1 for c in text if c.isupper()) / max(len(text), 1),
        "first_person_rate": first_person / n_words,
        "avg_word_len": sum(len(w) for w in words) / n_words,
        "text_len": len(text),
    }


SIGNAL_COLS = [
    "burstiness", "mattr", "flesch_reading_ease", "flesch_kincaid_grade",
    "exclamation_rate", "caps_ratio", "first_person_rate", "avg_word_len",
    "mean_sentence_len", "n_sentences",
]


class TemplateReuse:
    """Max TF-IDF similarity to TRAIN flagged texts — fitted on train only.

    Self-match matters here. The train AI texts ARE the reference matrix, so
    scoring one of them naively returns 1.0 (it matches itself), every train
    AI text scores 1.0, and any threshold derived from that distribution is
    unreachable by a held-out text — the rule then never fires. Training rows
    must therefore be scored with their own column masked out.
    """

    def __init__(self) -> None:
        self.vec = TfidfVectorizer(ngram_range=(1, 2), sublinear_tf=True,
                                   min_df=2, max_features=8000)
        self.train_ai_matrix = None
        self._row_of: dict[str, int] = {}

    def fit(self, train_ai_texts: list[str]) -> "TemplateReuse":
        try:
            self.train_ai_matrix = self.vec.fit_transform(train_ai_texts)
        except ValueError:
            # min_df=2 prunes every term when the corpus is tiny or shares no
            # vocabulary. Fall back rather than take down the whole agent.
            self.vec = TfidfVectorizer(ngram_range=(1, 2), sublinear_tf=True,
                                       min_df=1, max_features=8000)
            self.train_ai_matrix = self.vec.fit_transform(train_ai_texts)
        self._row_of = {t: i for i, t in enumerate(train_ai_texts)}
        return self

    def score_many(self, texts: list[str], exclude_self: bool = False) -> np.ndarray:
        if self.train_ai_matrix is None or self.train_ai_matrix.shape[0] == 0:
            return np.zeros(len(texts))
        sims = cosine_similarity(self.vec.transform(texts), self.train_ai_matrix)
        if exclude_self:
            for i, text in enumerate(texts):
                row = self._row_of.get(text)
                if row is not None:
                    sims[i, row] = -1.0
        return sims.max(axis=1).clip(min=0.0)

    def score(self, text: str) -> float:
        return float(self.score_many([text])[0])


# ---------------------------------------------------------------------------
# LLM zero-shot detector + reasoning
# ---------------------------------------------------------------------------

LLM_SYSTEM_PROMPT = (
    "You are a forensic analyst for a payments company. Decide whether a piece "
    "of user-submitted text (product review or dispute narrative) was written "
    "by a human or generated by an AI/LLM. Base your judgment on textual "
    "forensics only: rhythm uniformity (low sentence-length variance), "
    "overly polished or generic phrasing, template-like structure, unnatural "
    "consistency of tone, absence of typos/idioms, and vocabulary repetition. "
    "Be cautious: short casual texts can go either way. Respond with JSON "
    'only: {"verdict": "ai" | "human", "confidence": 0-1, "reasons": ["...", "..."]}'
)

DETECTOR_MODEL = "anthropic/claude-haiku-4.5"


def llm_classify(text: str, domain: str) -> dict:
    prompt = f"Text type: {domain} narrative.\n\nText:\n{text}\n\nJSON verdict:"
    out = chat_json(
        [{"role": "system", "content": LLM_SYSTEM_PROMPT},
         {"role": "user", "content": prompt}],
        model=DETECTOR_MODEL, temperature=0.0, max_tokens=300,
    )
    verdict = out.get("verdict", "human")
    if verdict not in ("ai", "human"):
        verdict = "human"
    return {
        "pred_ai": int(verdict == "ai"),
        "confidence": float(out.get("confidence", 0.5)),
        "reasons": list(out.get("reasons", []))[:4],
    }


# ---------------------------------------------------------------------------
# Case construction
# ---------------------------------------------------------------------------

def make_case(row: pd.Series, sig: dict, llm: dict | None,
              fallback_confidence: float = 0.5) -> Case:
    evidence = []
    if llm:
        for i, reason in enumerate(llm["reasons"]):
            evidence.append(Evidence(
                f"llm_reason_{i+1}", reason,
                round(0.20 * llm["confidence"] / max(len(llm["reasons"]), 1), 4)))
    if sig["burstiness"] < 0.35:
        evidence.append(Evidence(
            "low_burstiness",
            f"sentence-length variance {sig['burstiness']:.2f} "
            f"(humans typically > 0.35)",
            RULES["low_burstiness"]["weight"]))
    if sig["flesch_kincaid_grade"] > 14:
        evidence.append(Evidence(
            "high_readability",
            f"Flesch-Kincaid grade {sig['flesch_kincaid_grade']:.1f} "
            f"(human reviews typically < 14)",
            RULES["high_readability"]["weight"]))
    if "template_reuse_score" in row and row["template_reuse_score"] > 0.35:
        evidence.append(Evidence(
            "template_reuse",
            f"TF-IDF similarity {row['template_reuse_score']:.2f} to known "
            f"AI-generated texts",
            RULES["template_reuse"]["weight"]))
    if sig["mattr"] < 0.55:
        evidence.append(Evidence(
            "low_lexical_diversity",
            f"lexical diversity (MATTR) {sig['mattr']:.2f} below human floor",
            RULES["low_lexical_diversity"]["weight"]))

    domain_label = "product review" if row["domain"] == "review" else "dispute narrative"
    conf = llm["confidence"] if llm else fallback_confidence
    # Content Forensics never auto-blocks: FN:FP is 2.33, below the policy
    # bar, because wrongly denying a real customer's dispute is close in cost
    # to paying out a fake one — and far worse for the customer.
    has_evidence = any(e.signal in RULES for e in evidence)
    decision, policy_why = decide("content_forensics", conf, has_evidence)
    reasoning = "; ".join(llm["reasons"]) if llm else "signal-based flag"
    return Case(
        source_agent="content_forensics",
        entity_id=str(row["prompt_group"]),
        entity_type="dispute" if row["domain"] == "dispute" else "document",
        evidence=evidence,
        confidence=conf,
        cost_estimate=25.0,   # proxy: wrongly denying a genuine customer text
        decision=decision,
        reasoning_text=(
            f"Flagged {domain_label} as likely AI-generated "
            f"(confidence {conf:.2f}). Forensic reasoning: {reasoning}. "
            f"Signals: burstiness={sig['burstiness']:.2f}, "
            f"readability grade={sig['flesch_kincaid_grade']:.1f}, "
            f"lexical diversity={sig['mattr']:.2f}. "
            f"Action `{decision}`: {policy_why}."
        ),
    )


