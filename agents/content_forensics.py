# Main
# ---------------------------------------------------------------------------

def parse_args() -> argparse.Namespace:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--limit-llm", type=int, default=0,
                    help="cap LLM-detector calls (smoke runs); 0 = all")
    ap.add_argument("--no-llm", action="store_true",
                    help="skip the LLM detector entirely (no API spend); the "
                         "rule and logistic-regression detectors still run")
    ap.add_argument("--max-cases", type=int, default=1000,
                    help="cap on cases written to the audit log this run")
    return ap.parse_args()


def _stable_hash(value: str) -> int:
    """Deterministic, uniformly distributed hash (Python's hash() is salted)."""
    return int(hashlib.md5(str(value).encode()).hexdigest()[:8], 16)


def group_split(df: pd.DataFrame) -> pd.DataFrame:
    """Assign train/heldout by prompt group, stratified by domain AND class.

    AI rows share one group id per topic, so held-out AI texts come from
    topics never seen in training and the template-reuse signal has to
    generalize instead of memorizing our own generation phrasing. Human rows
    carry unique corpus ids, so the same rule gives them a random row split.

    Two things this must not get wrong, both of which it previously did:
      - A naive `sum(ord(c)) % 100` hash is nearly constant across strings
        that share a prefix. Every AI group ("dispute_topic00"...) collided
        into one end of the range and every human corpus id into the other,
        so the split lined up exactly with the label: held-out ended up
        100% AI, no negatives, and precision was trivially 1.0.
      - Even with a good hash, per-group Bernoulli draws can leave a class
        or a domain badly under-represented at this sample size.
    Selecting a fixed fraction of groups by hash RANK within each
    (domain, class) stratum removes both failure modes and stays
    deterministic across runs.
    """
    df = df.copy()
    df["split"] = "train"
    for (domain, is_ai), block in df.groupby(["domain", "is_ai_generated"]):
        groups = sorted(block["prompt_group"].astype(str).unique(),
                        key=_stable_hash)
        n_held = max(1, round(len(groups) * HELDOUT_GROUP_FRACTION))
        held = set(groups[:n_held])
        mask = (df["domain"] == domain) & (df["is_ai_generated"] == is_ai) & \
               df["prompt_group"].astype(str).isin(held)
        df.loc[mask, "split"] = "heldout"
    return df


def main() -> None:
    args = parse_args()

    df = pd.read_csv(DATASET_PATH)
    df = group_split(df)
    train = df[df["split"] == "train"].copy()
    held = df[df["split"] == "heldout"].copy()
    for dom in ("review", "dispute"):
        t, h = train[train["domain"] == dom], held[held["domain"] == dom]
        print(f"{dom:<8} train: {len(t):>4} "
              f"(AI {int((t['is_ai_generated']==1).sum())})   "
              f"heldout: {len(h):>4} (AI {int((h['is_ai_generated']==1).sum())})")

    # --- signals ------------------------------------------------------------
    t0 = time.perf_counter()
    sig_train = pd.DataFrame([compute_signals(t) for t in train["text"]],
                             index=train.index)
    sig_held = pd.DataFrame([compute_signals(t) for t in held["text"]],
                            index=held.index)
    reuse = TemplateReuse().fit(
        train.loc[train["is_ai_generated"] == 1, "text"].tolist())
    # Train rows are scored with their own column masked (see TemplateReuse);
    # held-out rows are not in the reference matrix, so no masking is needed.
    train["template_reuse_score"] = reuse.score_many(
        train["text"].tolist(), exclude_self=True)
    held["template_reuse_score"] = reuse.score_many(held["text"].tolist())
    signal_time = time.perf_counter() - t0

    # --- detector 1: rule threshold (tuned on train only) --------------------
    burst_floor = float(np.quantile(sig_train.loc[train["is_ai_generated"] == 0,
                                                   "burstiness"], 0.10))
    grade_ceil = float(np.quantile(sig_train.loc[train["is_ai_generated"] == 0,
                                                 "flesch_kincaid_grade"], 0.90))
    reuse_thr = float(np.quantile(train.loc[train["is_ai_generated"] == 1,
                                             "template_reuse_score"], 0.25))
    print(f"\nRule thresholds (train): burstiness floor {burst_floor:.2f}, "
          f"grade ceiling {grade_ceil:.1f}, reuse threshold {reuse_thr:.2f}")

    rule_pred = (
        (sig_held["burstiness"] < burst_floor).astype(int)
        | (sig_held["flesch_kincaid_grade"] > grade_ceil).astype(int)
        | (held["template_reuse_score"] > reuse_thr).astype(int)
    )

    # --- detector 2: logistic regression on signals --------------------------
    X_train = pd.concat([sig_train[SIGNAL_COLS],
                         train["template_reuse_score"].rename("template_reuse_score")],
                        axis=1)
    X_held = pd.concat([sig_held[SIGNAL_COLS],
                        held["template_reuse_score"].rename("template_reuse_score")],
                       axis=1)
    # Scaling is not optional here: these signals span three orders of
    # magnitude (caps_ratio ~0.01 vs flesch_reading_ease ~0-100). Unscaled,
    # the solver collapsed to predicting the majority class for every row.
    lr = make_pipeline(StandardScaler(), LogisticRegression(max_iter=2000, C=1.0))
    lr.fit(X_train, train["is_ai_generated"])
    lr_score = lr.predict_proba(X_held)[:, 1]
    lr_pred = (lr_score >= 0.5).astype(int)

    # --- detector 3: LLM zero-shot + reasoning -------------------------------
    llm_start = 0 if args.no_llm else min(len(held), args.limit_llm or len(held))
    t0 = time.perf_counter()
    llm_out: dict[int, dict] = {}
    for i, (idx, row) in enumerate(held.head(llm_start).iterrows()):
        llm_out[idx] = llm_classify(row["text"], row["domain"])
        if (i + 1) % 25 == 0:
            print(f"  LLM detector {i+1}/{llm_start}")
    llm_time = time.perf_counter() - t0
    llm_eval = held.head(llm_start)
    llm_pred = np.array([llm_out[i]["pred_ai"] for i in llm_eval.index])
    llm_conf = np.array([llm_out[i]["confidence"] for i in llm_eval.index])
    if llm_start:
        print(f"  LLM detector evaluated on {llm_start} of {len(held)} "
              f"held-out texts")

    # --- report ---------------------------------------------------------------
    results = {
        "rule_threshold": binary_metrics(held["is_ai_generated"], rule_pred),
        "logistic_regression": {
            **binary_metrics(held["is_ai_generated"], lr_pred),
            "pr_auc": pr_auc(held["is_ai_generated"], lr_score),
        },
    }
    if llm_start:
        y_llm = llm_eval["is_ai_generated"]
        results["llm_zeroshot"] = {
            **binary_metrics(y_llm, llm_pred),
            "mean_confidence": round(float(llm_conf.mean()), 3),
            "n_evaluated": int(llm_start),
            "n_heldout_total": int(len(held)),
        }
    else:
        print("\nLLM detector SKIPPED (--no-llm): rule and logistic-regression "
              "detectors below are complete; the reasoning layer is not "
              "evaluated in this run.")
    for name, m in results.items():
        print(format_report(f"[held-out] {name}", m))
    print(f"\nSignal extraction: {signal_time/max(len(df),1)*1000:.1f} ms/text; "
          f"LLM detector: {llm_time/max(llm_start,1):.2f} s/text "
          f"({llm_start} calls, disk-cached on re-runs)")

    # signal quality: standardized mean gap between classes per signal
    ai_mask = held["is_ai_generated"] == 1
    sep = {}
    for col in SIGNAL_COLS:
        a, b = sig_held.loc[ai_mask, col], sig_held.loc[~ai_mask, col]
        sd = pd.concat([a, b]).std() or 1.0
        sep[col] = round(float((a.mean() - b.mean()) / sd), 3)
    a = held.loc[ai_mask, "template_reuse_score"]
    b = held.loc[~ai_mask, "template_reuse_score"]
    sd = pd.concat([a, b]).std() or 1.0
    sep["template_reuse_score"] = round(float((a.mean() - b.mean()) / sd), 3)
    print(f"\nSignal separation (|effect| > 0.5 meaningful): {sep}")

    # --- cases for flagged held-out texts --------------------------------------
    # Which detector supplies the flags depends on what ran: the LLM when it
    # was called, otherwise the logistic-regression detector. Either way the
    # audit log gets populated — case files are not an LLM-only feature.
    if llm_start:
        flagged_idx = [i for i in llm_eval.index if llm_out[i]["pred_ai"] == 1]
        flag_source = "llm_zeroshot"
    else:
        flagged_idx = [i for i, pred in zip(held.index, lr_pred) if pred == 1]
        flag_source = "logistic_regression"
    cases = []
    for idx in flagged_idx[: args.max_cases]:
        row = held.loc[idx]
        sig = sig_held.loc[idx].to_dict()
        conf = float(lr_score[held.index.get_loc(idx)])
        cases.append(make_case(row, sig, llm_out.get(idx), conf))
    conn = connect(DEFAULT_DB_PATH)
    insert_cases(conn, cases)
    print(f"\nFlags for case files came from: {flag_source}")
    print(f"Wrote {len(cases)} content_forensics cases; audit log now holds "
          f"{count_cases(conn, 'content_forensics')} content_forensics / "
          f"{count_cases(conn)} total")

    # --- save ------------------------------------------------------------------
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    report = {
        "agent": "content_forensics",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "dataset": {
            "n_total": len(df), "n_train": len(train), "n_heldout": len(held),
            "heldout_fraction_groups": HELDOUT_GROUP_FRACTION,
            "split": "group-based for AI (unseen topics), hashed-id for human",
            "generator_models": sorted(
                df.loc[df["is_ai_generated"] == 1, "source"].unique().tolist()),
            "detector_model": DETECTOR_MODEL,
            "caveats": [
                "AI texts generated by minimax/gemma; detector is Claude — "
                "different families, so no self-recognition advantage, but "
                "both are 2026-era LLMs",
                "human reviews from Amazon corpus, disputes from CFPB "
                "complaints (US finance domain); KYC self-descriptions "
                "out of eval scope (no public genuine-human corpus)",
            ],
        },
        "results": results,
        "rule_thresholds": {
            "burstiness_floor": round(burst_floor, 3),
            "fk_grade_ceiling": round(grade_ceil, 2),
            "template_reuse_threshold": round(reuse_thr, 3),
        },
        "signal_separation_heldout": sep,
        "timing": {
            "signal_ms_per_text": round(signal_time / max(len(df), 1) * 1000, 1),
            "llm_s_per_text": round(llm_time / max(llm_start, 1), 2),
        },
        "cases_written": len(cases),
        "case_flag_source": flag_source,
        "lr_coefficients": {
            c: round(float(v), 3)
            for c, v in zip(X_train.columns,
                            lr.named_steps["logisticregression"].coef_[0])
        },
    }
    out_path = RESULTS_DIR / "content_forensics_metrics.json"
    with open(out_path, "w") as f:
        json.dump(report, f, indent=2)
    print(f"Saved metrics to {out_path}")


if __name__ == "__main__":
    main()
